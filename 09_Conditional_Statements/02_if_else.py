# if-else statement - 5 examples

age = 17
if age >= 18:
    print("Adult")
else:
    print("Minor")

password = "1234"
if password == "admin":
    print("Access granted")
else:
    print("Access denied")

speed = 50
if speed > 60:
    print("Over Speed Limit")
else:
    print("Within Speed Limit")

number = -5
if number >= 0:
    print("Positive number")
else:
    print("Negative number")

score = 40
if score >= 50:
    print("Pass")
else:
    print("Fail")
