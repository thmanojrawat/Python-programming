# if statement - 5 examples

temperature = 30
if temperature > 25:
    print("It's a hot day.")

number = 10
if number % 2 == 0:
    print("Even number.")

name = "Alice"
if name == "Alice":
    print("Hello, Alice!")

marks = 85
if marks >= 80:
    print("You passed with distinction.")

is_raining = True
if is_raining:
    print("Take an umbrella.")
